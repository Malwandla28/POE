package TestClasses;

import com.mycompany.registrationloginfeature.Message;
import static org.junit.jupiter.api.Assertions.*;

import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

public class MessageTest {

    // Test Data: Message 1 and Message 2 (a fixed ID is used so the hash is predictable)
    private static final String ID = "0012345678";
    private static final String RECIPIENT_1 = "+27718693002";
    private static final String MESSAGE_1 = "Hi Mike, can you join us for dinner tonight?";
    private static final String RECIPIENT_2 = "08575975889";
    private static final String MESSAGE_2 = "Hi Keegan, did you receive the payment?";

    private Message msg1;
    private Message msg2;
    private Path jsonFile;

    @BeforeEach
    public void setUp(@TempDir Path tempDir) {
        Message.clearAll();
        jsonFile = tempDir.resolve("messages.json");
        Message.setStorageFile(jsonFile);
        msg1 = new Message(ID, 0, RECIPIENT_1, MESSAGE_1);
        msg2 = new Message(ID, 1, RECIPIENT_2, MESSAGE_2);
    }

    // ---------------- Message length ----------------

    @Test
    public void testMessageLengthSuccess() {
        assertEquals("Message ready to send.", msg1.checkMessageLength());
    }

    @Test
    public void testMessageLengthFailure() {
        String longText = "a".repeat(260);
        Message tooLong = new Message(ID, 0, RECIPIENT_1, longText);
        assertEquals("Message exceeds 250 characters by 10; please reduce the size.",
                tooLong.checkMessageLength());
    }

    // ---------------- Recipient number ----------------

    @Test
    public void testRecipientCellSuccess() {
        assertEquals("Cell phone number successfully captured.", msg1.checkRecipientCell());
    }

    @Test
    public void testRecipientCellFailure() {
        assertEquals("Cell phone number is incorrectly formatted or does not contain an international code. "
                + "Please correct the number and try again.", msg2.checkRecipientCell());
    }

    // ---------------- Message hash ----------------

    @Test
    public void testMessageHashTestCase1() {
        assertEquals("00:0:HITONIGHT", msg1.createMessageHash());
    }

    @Test
    public void testMessageHashesInLoop() {
        String[] messages = {MESSAGE_1, MESSAGE_2, "Hello there", "Thanks"};
        String[] expected = {"00:0:HITONIGHT", "00:1:HIPAYMENT", "00:2:HELLOTHERE", "00:3:THANKSTHANKS"};

        for (int i = 0; i < messages.length; i++) {
            Message m = new Message(ID, i, RECIPIENT_1, messages[i]);
            assertEquals(expected[i], m.createMessageHash());
        }
    }

    // ---------------- Message ID ----------------

    @Test
    public void testMessageIDCreated() {
        assertEquals("Message ID generated: " + ID, msg1.returnMessageIDMessage());
        assertTrue(msg1.checkMessageID());
    }

    @Test
    public void testAutoGeneratedIDIsTenCharacters() {
        Message m = new Message(0, RECIPIENT_1, MESSAGE_1);
        assertEquals(10, m.getMessageID().length());
        assertTrue(m.checkMessageID());
    }

    // ---------------- Message sent ----------------

    @Test
    public void testSendMessage() {
        assertEquals("Message successfully sent.", msg1.sentMessage(1));
    }

    @Test
    public void testDisregardMessage() {
        assertEquals("Press 0 to delete the message.", msg2.sentMessage(2));
    }

    @Test
    public void testStoreMessage() throws Exception {
        assertEquals("Message successfully stored.", msg1.sentMessage(3));
        String json = Files.readString(jsonFile);
        assertTrue(json.contains("\"messageHash\": \"00:0:HITONIGHT\""));
        assertTrue(json.contains(RECIPIENT_1));
    }

    // ---------------- Totals ----------------

    @Test
    public void testReturnTotalMessages() {
        msg1.sentMessage(1); // send
        msg2.sentMessage(2); // discard
        assertEquals(1, msg1.returnTotalMessages());
    }

    @Test
    public void testPrintMessages() {
        msg1.sentMessage(1);
        String output = msg1.printMessages();
        assertTrue(output.contains(ID));
        assertTrue(output.contains("00:0:HITONIGHT"));
        assertTrue(output.contains(RECIPIENT_1));
        assertTrue(output.contains(MESSAGE_1));
    }
}
